import fs from "node:fs";
import path from "node:path";
const ROOT = "D:/Projects/ronaldo-stats";

// 1. .gitignore the translator's working files
const gi = path.join(ROOT, ".gitignore");
let g = fs.readFileSync(gi, "utf8");
if (!g.includes("*.missing.json")) {
  g = g.replace(/\n?$/, "\n\n# translator working files (regenerated by scripts/list-missing-shell.mjs)\nsrc/i18n/shell/*.missing.json\n");
  fs.writeFileSync(gi, g, "utf8");
  console.log(".gitignore updated");
}

// 2. the verification gate in package.json
const pp = path.join(ROOT, "package.json");
const pkg = JSON.parse(fs.readFileSync(pp, "utf8"));
pkg.scripts["verify:all"] = "node scripts/verify-all.mjs";
pkg.scripts["verify:espn"] = "node scripts/cross-check-espn.mjs";
pkg.scripts["build:calendar"] = "node scripts/extract-goal-calendar.mjs && node scripts/build-birthday-goals.mjs && node scripts/fill-calendar-gaps.mjs";
fs.writeFileSync(pp, JSON.stringify(pkg, null, 2) + "\n", "utf8");
console.log("package.json scripts:", Object.keys(pkg.scripts).length);

// 3. robots.txt — make sure it is Ronaldo's and allows the crawler surface
const rp = path.join(ROOT, "public", "robots.txt");
const r = fs.readFileSync(rp, "utf8");
const lines = r.split(/\r?\n/);
const need = ["User-agent: *", "Sitemap:", "Disallow: /admin", "Allow: /"];
for (const n of need) {
  if (!r.includes(n)) console.log("robots.txt is missing: " + n);
}
console.log("robots.txt lines:", lines.length, "| Sitemap entry:", /Sitemap:\s*https:\/\/www\.ronaldostats\.site/.test(r));
